export function getEmojiForOption(text: string): string {
  const normalized = text.toLowerCase().trim();
  // Búsqueda exacta
  if (optionEmojis[normalized]) return optionEmojis[normalized];
  // Búsqueda parcial (si el texto contiene la palabra clave)
  for (const key of Object.keys(optionEmojis)) {
    if (normalized.includes(key)) return optionEmojis[key];
  }
  return '✨';
}

